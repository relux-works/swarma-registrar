// A repository-local graft must not turn an independently signed root into a
// descendant and install it through the real loader/store. The same candidate
// without the graft is the nearby rollback control; a genuine descendant then
// installs exactly once. Test keys are ephemeral.
func TestReviewGitGrafts(t *testing.T) {
	f := newGitFixture(t)
	write(t, filepath.Join(f.dir, "enrollments/a.json"), enrollmentFixture(t), 0600)
	f.commit(t, true)
	old := f.pin
	g := f.adapter(t)
	entries, err := g.Read(context.Background())
	if err != nil {
		t.Fatal("read old control")
	}
	policy, err := publicEnrollment.NewPolicy("example.org", testPublic(1), map[string]bool{"host-a": false})
	if err != nil {
		t.Fatal("policy")
	}
	store, _ := newStore(t)
	counted := &countStore{Store: store}
	loader := registry.Loader{ObjectFormat: "sha1", Policy: policy, Verifier: g, Store: counted}
	_, retained, err := loader.Load(registry.Input{Revision: old, Entries: entries, FirstUse: true})
	if err != nil {
		t.Fatal("bootstrap control")
	}
	counted.calls = 0
	tree := command(t, f.dir, "git", "rev-parse", old+"^{tree}")
	candidate := command(t, f.dir, "git", "commit-tree", "-S", "-m", "Independent signed fixture", tree)
	f.pin = candidate
	g = f.adapter(t)
	loader.Verifier = g
	if ok, e := g.Descends(candidate, old); e != nil || ok {
		t.Fatal("independent root baseline")
	}
	in := registry.Input{Revision: candidate, Entries: entries, Retained: retained, Reconciled: true}
	_, _, err = loader.Load(in)
	wantCode(t, err, registry.RegistryRollback)
	write(t, filepath.Join(f.dir, ".git/info/grafts"), []byte(candidate+" "+old+"\n"), 0600)
	snapshot, next, err := loader.Load(in)
	if err == nil || snapshot != nil || next != nil {
		t.Fatalf("grafted unrelated root became authority: error_nil=%t snapshot=%t next=%t", err == nil, snapshot != nil, next != nil)
	}
	wantCode(t, err, registry.RegistryRollback)
	state, err := store.Load()
	if err != nil || state.HighWater.Revision != old || counted.calls != 0 {
		t.Fatal("rollback refusal changed durable authority")
	}
	descendant := command(t, f.dir, "git", "commit-tree", "-S", "-p", old, "-m", "Descendant signed fixture", tree)
	f.pin = descendant
	loader.Verifier = f.adapter(t)
	in.Revision = descendant
	snapshot, next, err = loader.Load(in)
	if err != nil || snapshot == nil || next == nil || next.Revision != descendant || counted.calls != 1 {
		t.Fatal("genuine descendant did not install once")
	}
}

type countStore struct {
	registry.Store
	calls int
}

func (s *countStore) Commit(previous *registry.HighWater, next registry.HighWater) error {
	s.calls++
	return s.Store.Commit(previous, next)
}

// Ambient Git variables, local trust/program settings, hooks and replace refs
// cannot change pinned objects or bypass the configured signer. No test invokes
// a network transport; trap programs only create a scratch marker if executed.
func TestReviewGitIsolation(t *testing.T) {
	f := newGitFixture(t)
	g := f.adapter(t)
	original := f.pin
	other := newGitFixture(t)
	t.Setenv("GIT_DIR", filepath.Join(other.dir, ".git"))
	t.Setenv("GIT_WORK_TREE", other.dir)
	t.Setenv("GIT_CONFIG_COUNT", "1")
	t.Setenv("GIT_CONFIG_KEY_0", "gpg.ssh.allowedSignersFile")
	t.Setenv("GIT_CONFIG_VALUE_0", other.allowed)
	marker := filepath.Join(tempDir(t), "executed")
	trap := filepath.Join(filepath.Dir(marker), "trap")
	// Paths are generated by t.TempDir and contain no quote characters.
	write(t, trap, []byte("#!/bin/sh\nprintf invoked > '"+marker+"'\nexit 0\n"), 0700)
	f.commit(t, false)
	unsigned := f.pin
	command(t, f.dir, "git", "replace", original, unsigned)
	for key, value := range map[string]string{"core.fsmonitor": trap, "core.hooksPath": filepath.Dir(trap), "gpg.ssh.program": trap, "gpg.ssh.allowedSignersFile": other.allowed} {
		command(t, f.dir, "git", "config", key, value)
	}
	entries, err := g.Read(context.Background())
	if err != nil || len(entries) != 1 || !bytes.Equal(entries[0].Bytes, []byte("first")) {
		t.Fatal("pinned signed control changed")
	}
	if _, err = os.Stat(marker); !os.IsNotExist(err) {
		t.Fatal("local program setting invoked")
	}
	g.pin = unsigned
	_, err = g.Read(context.Background())
	wantCode(t, err, registry.RegistryUnavailable)
	for _, pin := range []string{"--help", "-c", strings.Repeat("a", 40) + "^{tree}", "main", "HEAD\n"} {
		if _, err = newGit(f.dir, pin, f.allowed, "sha1", rootFixture); err == nil {
			t.Fatal("nonliteral revision accepted")
		}
	}
}

// Signed oversized blobs still obey aggregate-before-per-file precedence; a
// restored small pinned blob remains readable through the same public source.
func TestReviewGitLimits(t *testing.T) {
	f := newGitFixture(t)
	good := f.pin
	for _, size := range []int{65537, registry.MaxBytes + 1} {
		write(t, filepath.Join(f.dir, "enrollments/a.json"), bytes.Repeat([]byte("x"), size), 0600)
		f.commit(t, true)
		_, err := f.adapter(t).Read(context.Background())
		code := registry.EnrollmentMalformed
		if size > registry.MaxBytes {
			code = registry.RegistryUnavailable
		}
		wantCode(t, err, code)
		bad := f.pin
		f.pin = good
		if _, err = f.adapter(t).Read(context.Background()); err != nil {
			t.Fatal("small pinned control")
		}
		f.pin = bad
	}
}
